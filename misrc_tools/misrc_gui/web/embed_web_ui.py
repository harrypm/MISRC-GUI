#!/usr/bin/env python3
"""Embed misrc_gui/web/index.html into misrc_gui/net/gui_web_ui_assets.c.

The generated C file is committed so every platform (including Android and
Windows single-EXE builds) compiles without needing Python at build time.

    python3 misrc_tools/misrc_gui/web/embed_web_ui.py          # regenerate
    python3 misrc_tools/misrc_gui/web/embed_web_ui.py --check  # CI/meson test
"""
import pathlib
import sys

WEB = pathlib.Path(__file__).resolve().parent
ROOT = WEB.parent.parent.parent
SRC = WEB / "index.html"
DST = WEB.parent / "net" / "gui_web_ui_assets.c"


def render(data: bytes) -> str:
    lines = [
        "/* GENERATED by misrc_gui/web/embed_web_ui.py from misrc_gui/web/index.html.",
        " * Do not edit by hand: edit index.html and rerun the script. */",
        '#include "gui_web_ui.h"',
        "",
        "const char gui_web_ui_index_html[] = {",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("    0x00")
    lines.append("};")
    lines.append(f"const size_t gui_web_ui_index_html_len = {len(data)}u;")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    data = SRC.read_bytes().replace(b"\r\n", b"\n")
    out = render(data)
    if "--check" in sys.argv[1:]:
        current = DST.read_text(encoding="ascii") if DST.exists() else ""
        if current.replace("\r\n", "\n") != out:
            print(f"{DST.relative_to(ROOT)} is out of date; run misrc_tools/misrc_gui/web/embed_web_ui.py")
            return 1
        print("web UI asset is up to date")
        return 0
    DST.write_text(out, encoding="ascii", newline="\n")
    print(f"wrote {DST.relative_to(ROOT)} ({len(data)} bytes of HTML)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
