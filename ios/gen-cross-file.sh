#!/usr/bin/env bash
# Generate a Meson cross-file for one iOS slice (device or simulator).
#
# Usage:
#   ./gen-cross-file.sh device   # iphoneos      -> ios/aarch64-ios.ini
#   ./gen-cross-file.sh sim      # iphonesimulator -> ios/aarch64-ios-sim.ini
#
# Env overrides:
#   DEPS_PREFIX - cross deps prefix (default derived from the slice)
#   IOS_MIN     - deployment target (default 17.0)
#
# The cross-file points Meson at the Xcode clang for the requested SDK
# (resolved via xcrun at generation time), the SDK sysroot, and a
# SLICE-SPECIFIC pkg-config wrapper generated into ios/.gen/ that pins
# PKG_CONFIG_LIBDIR to the slice prefix so Meson can never resolve host
# .pc files (arm64 macOS libs would otherwise silently link into the iOS
# binary). Mirrors android/gen-cross-file.sh.
#
# Why a generator instead of a static .ini: SDK paths move with every
# Xcode update and prefixes differ per slice/host, and Meson cross-files
# do not expand env vars.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"

SLICE="${1:-}"
case "$SLICE" in
  device)
    SDK=iphoneos
    INI="$SCRIPT_DIR/aarch64-ios.ini"
    DEFAULT_PREFIX="$REPO_ROOT/.deps/install-ios-arm64"
    TARGET_TRIPLE="arm64-apple-ios${IOS_MIN:-17.0}"
    ;;
  sim)
    SDK=iphonesimulator
    INI="$SCRIPT_DIR/aarch64-ios-sim.ini"
    DEFAULT_PREFIX="$REPO_ROOT/.deps/install-ios-sim-arm64"
    TARGET_TRIPLE="arm64-apple-ios${IOS_MIN:-17.0}-simulator"
    ;;
  *)
    echo "Usage: $0 device|sim" >&2
    exit 1
    ;;
esac

IOS_MIN="${IOS_MIN:-17.0}"
DEPS_PREFIX="${DEPS_PREFIX:-$DEFAULT_PREFIX}"
mkdir -p "$DEPS_PREFIX"
DEPS_PREFIX="$(cd -- "$DEPS_PREFIX" && pwd)"

# Resolve the toolchain through xcrun (requires the Xcode license to be
# accepted; xcrun fails with a clear error otherwise).
SDK_PATH="$(xcrun --sdk "$SDK" --show-sdk-path)"
CC="$(xcrun --sdk "$SDK" --find clang)"
CXX="$(xcrun --sdk "$SDK" --find clang++)"
# Xcode 26's toolchain bin has no llvm-ar/llvm-ranlib/llvm-strip (xcrun cannot
# find them); it ships BSD ar/ranlib/strip + llvm-nm alongside clang. Resolve
# everything relative to the clang binary's directory.
TOOLCHAIN_BIN="$(dirname "$CC")"
AR="$TOOLCHAIN_BIN/ar"
RANLIB="$TOOLCHAIN_BIN/ranlib"
STRIP="$TOOLCHAIN_BIN/strip"
NM="$TOOLCHAIN_BIN/llvm-nm"
LD="$CC"  # clang drives the final app link

for t in "$CC" "$CXX" "$AR" "$RANLIB" "$STRIP" "$NM"; do
  [[ -x "$t" ]] || { echo "ERROR: tool not found/executable: $t (run sudo xcodebuild -license first)" >&2; exit 1; }
done

# Per-slice pkg-config wrapper with the prefix baked in (Meson does not
# inherit our shell env when it spawns binaries).
GEN_DIR="$SCRIPT_DIR/.gen"
mkdir -p "$GEN_DIR"
PC_WRAPPER="$GEN_DIR/pkg-config-$SDK"
cat > "$PC_WRAPPER" <<EOF
#!/usr/bin/env bash
# Auto-generated by ios/gen-cross-file.sh ($SDK slice) — do not edit.
set -euo pipefail
export PKG_CONFIG_LIBDIR="$DEPS_PREFIX/lib/pkgconfig:$DEPS_PREFIX/lib64/pkgconfig"
export PKG_CONFIG_PATH=
export PKG_CONFIG_SYSROOT_DIR=/
exec pkg-config --static "\$@"
EOF
chmod +x "$PC_WRAPPER"

# Common compile flags for both C and C++ (C++ needed by openh264).
# NOTE: Apple clang rejects the combined '-target=X' / '-isysroot=X' argv
# forms (meson passes them through verbatim); use two-element form.
CFLAGS_COMMON=("-target" "$TARGET_TRIPLE" "-isysroot" "$SDK_PATH" "-fPIC")
OBJCFLAGS_COMMON=("-target" "$TARGET_TRIPLE" "-isysroot" "$SDK_PATH" "-fPIC" "-fobjc-arc")

LINK_COMMON=("-target" "$TARGET_TRIPLE" "-isysroot" "$SDK_PATH"
  "-L$DEPS_PREFIX/lib" "-L$DEPS_PREFIX/lib64")

# join args into a meson list body: 'a', 'b', 'c' (IFS tricks do NOT insert
# multi-char separators; build it explicitly).
join() {
  local out="" first=1 a
  for a in "$@"; do
    if (( first )); then out="'$a'"; first=0; else out+=", '$a'"; fi
  done
  printf '%s' "$out"
}

cat > "$INI" <<EOF
# Auto-generated by ios/gen-cross-file.sh — do not edit by hand.
# Target: $TARGET_TRIPLE (SDK: $SDK, min iOS $IOS_MIN).
# Regenerate after an Xcode update or moving DEPS_PREFIX.

[binaries]
c = '$CC'
cpp = '$CXX'
objc = '$CC'
ar = '$AR'
ld = '$LD'
strip = '$STRIP'
nm = '$NM'
ranlib = '$RANLIB'
pkg-config = '$PC_WRAPPER'
cmake = '$(command -v cmake)'

[built-in options]
c_args = [$(join "${CFLAGS_COMMON[@]}")]
cpp_args = [$(join "${CFLAGS_COMMON[@]}")]
objc_args = [$(join "${OBJCFLAGS_COMMON[@]}")]
c_link_args = [$(join "${LINK_COMMON[@]}")]
cpp_link_args = [$(join "${LINK_COMMON[@]}")]
objc_link_args = [$(join "${LINK_COMMON[@]}")]

[properties]
sys_root = '$SDK_PATH'
# Device binaries cannot run on the host; simulator binaries can (arm64
# mac), but misrc_tools/meson.build uses no cc.run() paths, so no exe
# wrapper is required either way.
needs_exe_wrapper = false
pkg_config_path = '$DEPS_PREFIX/lib/pkgconfig:$DEPS_PREFIX/lib64/pkgconfig'

[host_machine]
system = 'ios'
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF

echo "Wrote $INI"
echo "Wrote $PC_WRAPPER"
echo "--- summary ---"
grep -E "^(c |cpp |objc |ar |ld |pkg-config|system |cpu_family |sys_root )" "$INI"
