#!/usr/bin/env bash
# Cross-build MISRC GUI dependencies for iOS (arm64, iOS 17.0+).
#
# Slices (SLICES env, default "device sim"):
#   device -> iphoneos        -> .deps/install-ios-arm64
#   sim    -> iphonesimulator -> .deps/install-ios-sim-arm64
#
# Deps (all static, per slice):
#   SDL2 2.30.12  - window/GL/touch/keyboard via UIKit+EAGL (raylib PLATFORM=SDL)
#   libFLAC 1.5.0 - hard-required by meson.build (flac.pc must report 1.5.0)
#   Opus 1.5.2    - Monitor/Remote Opus audio
#   Zstandard 1.5.7 - M-Server/M-Client preview
#   FFTW 3.3.10   - single precision (fftw3f), required by misrc_gui
#   libsoxr 0.1.3 - resampler (required for Opus audio monitor)
#   OpenH264      - vendored third_party/openh264 (meson cross-build)
#   hsdaoh stub   - ios/hsdaoh_stub (no-USB platform, zero devices)
#   raylib 5.5    - PLATFORM=SDL + GRAPHICS_API_OPENGL_ES3
#
# libusb/libuvc/hsdaoh-real are NOT built: iOS has no libusb backend and no
# public USB host API, so FX3/DdD/RTLSDR/hsdaoh capture is impossible. The
# stub libhsdaoh keeps gui_capture.c linkable unchanged.
#
# Env:
#   SLICES    - "device", "sim", or "device sim" (default)
#   DEPS_ROOT - parent of the install prefixes (default $REPO_ROOT/.deps)
#   DEPS_SRC_DIR - source/build dir (default $REPO_ROOT/.deps/src-ios)
#   JOBS      - parallel build count (default: CPU count)
#   IOS_MIN   - deployment target (default 17.0)
#
# Idempotent: a dep is skipped when its .pc in the slice prefix already
# reports the expected version. Mirrors android/build-deps-android.sh.
#
# REQUIRES: Xcode + accepted license (sudo xcodebuild -license).
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"

SLICES="${SLICES:-device sim}"
DEPS_ROOT="${DEPS_ROOT:-$REPO_ROOT/.deps}"
DEPS_SRC_DIR="${DEPS_SRC_DIR:-$REPO_ROOT/.deps/src-ios}"
JOBS="${JOBS:-$(sysctl -n hw.ncpu 2>/dev/null || nproc)}"
IOS_MIN="${IOS_MIN:-17.0}"

# Source pins (mirror android/build-deps-android.sh where shared).
FLAC_VERSION=1.5.0
FLAC_TARBALL="flac-${FLAC_VERSION}.tar.xz"
FLAC_URL="https://github.com/xiph/flac/releases/download/${FLAC_VERSION}/${FLAC_TARBALL}"
FLAC_SHA256="f2c1c76592a82ffff8413ba3c4a1299b6c7ab06c734dee03fd88630485c2b920"

OPUS_VERSION=1.5.2
OPUS_TARBALL="opus-${OPUS_VERSION}.tar.gz"
OPUS_URL="https://github.com/xiph/opus/releases/download/v${OPUS_VERSION}/${OPUS_TARBALL}"
OPUS_SHA256="65c1d2f78b9f2fb20082c38cbe47c951ad5839345876e46941612ee87f9a7ce1"

ZSTD_VERSION=1.5.7
ZSTD_TARBALL="zstd-${ZSTD_VERSION}.tar.gz"
ZSTD_URL="https://github.com/facebook/zstd/releases/download/v${ZSTD_VERSION}/${ZSTD_TARBALL}"
ZSTD_SHA256="eb33e51f49a15e023950cd7825ca74a4a2b43db8354825ac24fc1b7ee09e6fa3"

FFTW_VERSION=3.3.10
FFTW_TARBALL="fftw-${FFTW_VERSION}.tar.gz"
FFTW_URL="https://fftw.org/${FFTW_TARBALL}"

SOXR_VERSION=0.1.3
SOXR_TARBALL="soxr-${SOXR_VERSION}-Source.tar.xz"
SOXR_URL="https://sourceforge.net/projects/soxr/files/${SOXR_TARBALL}/download"

SDL2_TAG="release-2.30.12"
RAYLIB_TAG="5.5"

log() { printf '[ios-deps] %s\n' "$*"; }
fail() { printf '[ios-deps] ERROR: %s\n' "$*" >&2; exit 1; }

# macOS shasum instead of sha256sum.
sha256_file() { shasum -a 256 "$1" | awk '{print $1}'; }

# download <url> <out> [sha256] — mirrors the android retry policy
# (--retry-all-errors: curl's default retry policy ignores SSL failures).
download() {
  local url="$1" out="$2" sha="${3:-}"
  if [[ -f "$out" && -s "$out" ]]; then
    log "cached $(basename "$out")"
  else
    log "downloading $(basename "$out")"
    curl -fL --retry 5 --retry-all-errors --retry-delay 2 --connect-timeout 30 -o "$out" "$url"
  fi
  if [[ -n "$sha" ]]; then
    local actual
    actual="$(sha256_file "$out")"
    [[ "$actual" == "$sha" ]] || fail "$(basename "$out") sha256 mismatch: expected $sha got $actual"
    log "sha256 ok $(basename "$out")"
  fi
}

mkdir -p "$DEPS_SRC_DIR"
VERS_FILE="$SCRIPT_DIR/deps-versions.txt"
{
  echo "# MISRC GUI iOS arm64 cross deps — versions + sources"
  echo "# Generated by ios/build-deps-ios.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Xcode: $(xcodebuild -version 2>/dev/null | head -1 | tr '\n' ' ')"
  echo "# Deployment target: iOS $IOS_MIN  Slices: $SLICES"
  echo
} > "$VERS_FILE"
record() { printf '%-18s %s\n' "$1" "$2" >> "$VERS_FILE"; }

# ---------------------------------------------------------------------------
# Per-slice build
# ---------------------------------------------------------------------------
for SLICE in $SLICES; do
  case "$SLICE" in
    device) SDK="iphoneos";       PREFIX="$DEPS_ROOT/install-ios-arm64";       INI="$SCRIPT_DIR/aarch64-ios.ini" ;;
    sim)    SDK="iphonesimulator"; PREFIX="$DEPS_ROOT/install-ios-sim-arm64";  INI="$SCRIPT_DIR/aarch64-ios-sim.ini" ;;
    *) fail "unknown slice '$SLICE' (use device|sim)" ;;
  esac

  log "===== slice: $SLICE (SDK $SDK, prefix $PREFIX) ====="

  # Cross-file + baked pkg-config wrapper for this slice (also used by the
  # openh264 meson build below).
  "$SCRIPT_DIR/gen-cross-file.sh" "$SLICE" >/dev/null
  [[ -f "$INI" ]] || fail "cross-file $INI missing after gen-cross-file.sh"

  PC_WRAPPER="$SCRIPT_DIR/.gen/pkg-config-$SDK"
  pc_version() { "$PC_WRAPPER" --modversion "$1" 2>/dev/null || true; }

  mkdir -p "$PREFIX" "$DEPS_SRC_DIR"
  export PKG_CONFIG_PATH="$PREFIX/lib/pkgconfig:$PREFIX/lib/lib64/pkgconfig:${PKG_CONFIG_PATH:-}"
  export CMAKE_PREFIX_PATH="$PREFIX:${CMAKE_PREFIX_PATH:-}"

  CC="$(xcrun --sdk "$SDK" --find clang)"
  CXX="$(xcrun --sdk "$SDK" --find clang++)"
  # Xcode 26 toolchain bin: BSD ar/ranlib/strip next to clang (no llvm-ar).
  TOOLCHAIN_BIN="$(dirname "$CC")"
  AR="$TOOLCHAIN_BIN/ar"
  STRIP_BIN="$TOOLCHAIN_BIN/strip"
  SDK_PATH="$(xcrun --sdk "$SDK" --show-sdk-path)"

  case "$SDK" in
    iphoneos)        TARGET_TRIPLE="arm64-apple-ios${IOS_MIN}" ;;
    iphonesimulator) TARGET_TRIPLE="arm64-apple-ios${IOS_MIN}-simulator" ;;
  esac

  # Minimal iOS toolchain file: hermetic prefix (FIND_ROOT_PATH ONLY),
  # static-only try-compiles (no run checks on cross targets), and the
  # cmake>=4 policy floor for older deps (soxr/FFTW declare cmake 2.8/3.x).
  GEN_DIR="$SCRIPT_DIR/.gen"
  TOOLCHAIN_FILE="$GEN_DIR/ios-toolchain-$SDK.cmake"
  cat > "$TOOLCHAIN_FILE" <<EOF
set(CMAKE_SYSTEM_NAME iOS)
set(CMAKE_OSX_SYSROOT "$SDK")
set(CMAKE_OSX_DEPLOYMENT_TARGET "$IOS_MIN")
set(CMAKE_FIND_ROOT_PATH "$PREFIX")
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)
set(CMAKE_POLICY_VERSION_MINIMUM 3.5)
# CRITICAL: an explicit -target triple. Apple clang 17 with ONLY -isysroot +
# -mios-simulator-version-min keeps the HOST (macOS) triple, so __IPHONEOS__
# stays undefined, availability macros resolve for macOS, and per-platform
# code (miniaudio iOS audio session, raylib __IPHONEOS__ paths) silently
# compiles the DESKTOP branches into iOS binaries.
set(CMAKE_C_FLAGS_INIT "-target $TARGET_TRIPLE")
set(CMAKE_CXX_FLAGS_INIT "-target $TARGET_TRIPLE")
set(CMAKE_OBJC_FLAGS_INIT "-target $TARGET_TRIPLE")
EOF

  cmake_x() {
    # NOTE: CMAKE_POLICY_VERSION_MINIMUM must be a -D: setting it only in the
    # toolchain file is too late for a project's own cmake_minimum_required()
    # (FFTW/soxr declare cmake 2.8/3.x; host cmake 4.x removed <3.5 support).
    cmake "$@" \
      -DCMAKE_TOOLCHAIN_FILE="$TOOLCHAIN_FILE" \
      -DCMAKE_BUILD_TYPE=Release \
      -DBUILD_SHARED_LIBS=OFF \
      -DCMAKE_INSTALL_PREFIX="$PREFIX" \
      -DCMAKE_FIND_ROOT_PATH="$PREFIX" \
      -DCMAKE_POLICY_VERSION_MINIMUM=3.5
  }

  # ---------------- SDL2 2.30.12 ----------------
  log "=== SDL2 $SDL2_TAG ($SDK) ==="
  if [[ "$(pc_version sdl2)" == "2.30.12" ]]; then
    log "skip (sdl2.pc already 2.30.12)"
  else
    SDL2_SRC="$DEPS_SRC_DIR/SDL"
    if [[ ! -d "$SDL2_SRC/.git" ]]; then
      rm -rf "$SDL2_SRC"
      git clone --depth 1 --branch "$SDL2_TAG" https://github.com/libsdl-org/SDL.git "$SDL2_SRC"
    fi
    rm -rf "$DEPS_SRC_DIR/sdl2-build-$SDK"
    # Static SDL2 + SDL2main (the iOS main glue that calls SDL_main).
    cmake_x -S "$SDL2_SRC" -B "$DEPS_SRC_DIR/sdl2-build-$SDK" \
      -DSDL_SHARED=OFF \
      -DSDL_STATIC=ON \
      -DSDL_TEST=OFF \
      -DSDL2_DISABLE_SDL2MAIN=OFF \
      -DSDL_RENDER=OFF \
      -DSDL_RENDER_METAL=OFF \
      -DSDL_VULKAN=OFF \
      -DSDL_X11=OFF \
      -DSDL_COCOA=OFF
    cmake --build "$DEPS_SRC_DIR/sdl2-build-$SDK" --parallel "$JOBS"
    cmake --install "$DEPS_SRC_DIR/sdl2-build-$SDK"
  fi
  [[ "$(pc_version sdl2)" == "2.30.12" ]] || fail "$SDK SDL2 not found in cross pkg-config after build"
  record "SDL2 ($SDK)" "$SDL2_TAG @ $(git -C "$DEPS_SRC_DIR/SDL" rev-parse --short HEAD 2>/dev/null || echo unknown)"

  # ---------------- libFLAC 1.5.0 ----------------
  log "=== libFLAC ${FLAC_VERSION} ($SDK) ==="
  if [[ "$(pc_version flac)" == "${FLAC_VERSION}" ]]; then
    log "skip (flac.pc already ${FLAC_VERSION})"
  else
    download "$FLAC_URL" "$DEPS_SRC_DIR/$FLAC_TARBALL" "$FLAC_SHA256"
    rm -rf "$DEPS_SRC_DIR/flac-src" "$DEPS_SRC_DIR/flac-build-$SDK"
    mkdir -p "$DEPS_SRC_DIR/flac-src"
    tar -xf "$DEPS_SRC_DIR/$FLAC_TARBALL" -C "$DEPS_SRC_DIR/flac-src" --strip-components=1
    cmake_x -S "$DEPS_SRC_DIR/flac-src" -B "$DEPS_SRC_DIR/flac-build-$SDK" \
      -DWITH_OGG=OFF -DBUILD_TESTING=OFF -DINSTALL_MANPAGES=OFF \
      -DBUILD_EXAMPLES=OFF -DBUILD_PROGRAMS=OFF -DBUILD_DOCS=OFF
    cmake --build "$DEPS_SRC_DIR/flac-build-$SDK" --parallel "$JOBS"
    cmake --install "$DEPS_SRC_DIR/flac-build-$SDK"
  fi
  [[ "$(pc_version flac)" == "${FLAC_VERSION}" ]] || fail "$SDK flac.pc missing after build"
  record "libFLAC ($SDK)" "${FLAC_VERSION} (sha256 ${FLAC_SHA256})"

  # ---------------- Opus 1.5.2 ----------------
  log "=== Opus ${OPUS_VERSION} ($SDK) ==="
  if [[ "$(pc_version opus)" == "${OPUS_VERSION}" ]]; then
    log "skip (opus.pc already ${OPUS_VERSION})"
  else
    download "$OPUS_URL" "$DEPS_SRC_DIR/$OPUS_TARBALL" "$OPUS_SHA256"
    rm -rf "$DEPS_SRC_DIR/opus-src" "$DEPS_SRC_DIR/opus-build-$SDK"
    mkdir -p "$DEPS_SRC_DIR/opus-src"
    tar -xf "$DEPS_SRC_DIR/$OPUS_TARBALL" -C "$DEPS_SRC_DIR/opus-src" --strip-components=1
    cmake_x -S "$DEPS_SRC_DIR/opus-src" -B "$DEPS_SRC_DIR/opus-build-$SDK" \
      -DCMAKE_INSTALL_LIBDIR=lib \
      -DOPUS_BUILD_SHARED_LIBRARY=OFF \
      -DOPUS_BUILD_PROGRAMS=OFF -DOPUS_BUILD_TESTING=OFF \
      -DOPUS_INSTALL_PKG_CONFIG_MODULE=ON -DOPUS_INSTALL_CMAKE_CONFIG_MODULE=OFF
    cmake --build "$DEPS_SRC_DIR/opus-build-$SDK" --parallel "$JOBS"
    cmake --install "$DEPS_SRC_DIR/opus-build-$SDK"
  fi
  [[ "$(pc_version opus)" == "${OPUS_VERSION}" ]] || fail "$SDK opus.pc missing after build"
  record "Opus ($SDK)" "${OPUS_VERSION} (sha256 ${OPUS_SHA256})"

  # ---------------- Zstandard 1.5.7 ----------------
  log "=== Zstandard ${ZSTD_VERSION} ($SDK) ==="
  if [[ "$(pc_version libzstd)" == "${ZSTD_VERSION}" ]]; then
    log "skip (libzstd.pc already ${ZSTD_VERSION})"
  else
    download "$ZSTD_URL" "$DEPS_SRC_DIR/$ZSTD_TARBALL" "$ZSTD_SHA256"
    rm -rf "$DEPS_SRC_DIR/zstd-src" "$DEPS_SRC_DIR/zstd-build-$SDK"
    mkdir -p "$DEPS_SRC_DIR/zstd-src"
    tar -xf "$DEPS_SRC_DIR/$ZSTD_TARBALL" -C "$DEPS_SRC_DIR/zstd-src" --strip-components=1
    cmake_x -S "$DEPS_SRC_DIR/zstd-src/build/cmake" -B "$DEPS_SRC_DIR/zstd-build-$SDK" \
      -DCMAKE_INSTALL_LIBDIR=lib \
      -DZSTD_BUILD_STATIC=ON -DZSTD_BUILD_SHARED=OFF \
      -DZSTD_BUILD_PROGRAMS=OFF -DZSTD_BUILD_TESTS=OFF \
      -DZSTD_MULTITHREAD_SUPPORT=OFF
    cmake --build "$DEPS_SRC_DIR/zstd-build-$SDK" --parallel "$JOBS"
    cmake --install "$DEPS_SRC_DIR/zstd-build-$SDK"
  fi
  [[ "$(pc_version libzstd)" == "${ZSTD_VERSION}" ]] || fail "$SDK libzstd.pc missing after build"
  record "Zstandard ($SDK)" "${ZSTD_VERSION} (sha256 ${ZSTD_SHA256})"

  # ---------------- FFTW 3.3.10 (fftw3f) ----------------
  log "=== FFTW ${FFTW_VERSION} ($SDK) ==="
  if [[ -n "$(pc_version fftw3f)" ]]; then
    log "skip (fftw3f.pc already $(pc_version fftw3f))"
  else
    download "$FFTW_URL" "$DEPS_SRC_DIR/$FFTW_TARBALL"
    FFTW_SHA="$(sha256_file "$DEPS_SRC_DIR/$FFTW_TARBALL")"
    rm -rf "$DEPS_SRC_DIR/fftw-src" "$DEPS_SRC_DIR/fftw-build-$SDK"
    mkdir -p "$DEPS_SRC_DIR/fftw-src"
    tar -xf "$DEPS_SRC_DIR/$FFTW_TARBALL" -C "$DEPS_SRC_DIR/fftw-src" --strip-components=1
    # ENABLE_FLOAT=ON builds libfftw3f + fftw3f.pc. No SIMD (parity with the
    # Android cross build; panels run on decimated data anyway).
    cmake_x -S "$DEPS_SRC_DIR/fftw-src" -B "$DEPS_SRC_DIR/fftw-build-$SDK" \
      -DENABLE_FLOAT=ON -DENABLE_MPI=OFF -DENABLE_OPENMP=OFF \
      -DBUILD_TESTS=OFF -DBUILD_SHARED_LIBS=OFF
    cmake --build "$DEPS_SRC_DIR/fftw-build-$SDK" --parallel "$JOBS"
    cmake --install "$DEPS_SRC_DIR/fftw-build-$SDK"
  fi
  record "FFTW ($SDK)" "${FFTW_VERSION} (sha256 ${FFTW_SHA:-$(sha256_file "$DEPS_SRC_DIR/$FFTW_TARBALL" 2>/dev/null || echo recorded-at-build)})"

  # ---------------- libsoxr 0.1.3 ----------------
  log "=== libsoxr ${SOXR_VERSION} ($SDK) ==="
  if [[ -n "$(pc_version soxr)" ]]; then
    log "skip (soxr.pc already $(pc_version soxr))"
  else
    download "$SOXR_URL" "$DEPS_SRC_DIR/$SOXR_TARBALL"
    SOXR_SHA="$(sha256_file "$DEPS_SRC_DIR/$SOXR_TARBALL")"
    rm -rf "$DEPS_SRC_DIR/soxr-src" "$DEPS_SRC_DIR/soxr-build-$SDK"
    mkdir -p "$DEPS_SRC_DIR/soxr-src"
    tar -xf "$DEPS_SRC_DIR/$SOXR_TARBALL" -C "$DEPS_SRC_DIR/soxr-src" --strip-components=1
    # NEON via WITH_SIMD on aarch64 (matches Android).
    cmake_x -S "$DEPS_SRC_DIR/soxr-src" -B "$DEPS_SRC_DIR/soxr-build-$SDK" \
      -DBUILD_TESTS=OFF -DWITH_SIMD=ON -DWITH_OPENMP=OFF
    cmake --build "$DEPS_SRC_DIR/soxr-build-$SDK" --parallel "$JOBS"
    cmake --install "$DEPS_SRC_DIR/soxr-build-$SDK"
  fi
  record "libsoxr ($SDK)" "${SOXR_VERSION} (sha256 ${SOXR_SHA:-$(sha256_file "$DEPS_SRC_DIR/$SOXR_TARBALL" 2>/dev/null || echo recorded-at-build)})"

  # ---------------- OpenH264 (vendored, meson cross-build) ----------------
  log "=== OpenH264 vendored ($SDK) ==="
  if [[ "$(pc_version openh264)" != "" ]]; then
    log "skip (openh264.pc already $(pc_version openh264))"
  else
    OPENH264_SHA="$(git -C "$REPO_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
    rm -rf "$DEPS_SRC_DIR/openh264-$SDK" "$DEPS_SRC_DIR/openh264-build-$SDK"
    cp -R "$REPO_ROOT/third_party/openh264" "$DEPS_SRC_DIR/openh264-$SDK"
    # Upstream ships meson.build; cross-build with the same slice cross-file
    # (C++ via the cpp entries; libc++ is the iOS default).
    # CRITICAL: --prefix MUST be explicit. Meson's default prefix on this
    # host is /opt/homebrew (Homebrew-present macOS default), which would
    # install iOS-sim artifacts into the HOST brew tree (this happened once:
    # run 2026-11-08 polluted /opt/homebrew; remediated via brew reinstall).
    meson setup "$DEPS_SRC_DIR/openh264-build-$SDK" "$DEPS_SRC_DIR/openh264-$SDK" \
      --cross-file "$INI" \
      --default-library static \
      --buildtype release \
      --prefix "$PREFIX" \
      -Dtests=disabled
    meson compile -C "$DEPS_SRC_DIR/openh264-build-$SDK" --jobs "$JOBS"
    meson install -C "$DEPS_SRC_DIR/openh264-build-$SDK"
  fi
  [[ -n "$(pc_version openh264)" ]] || fail "$SDK openh264.pc missing after build"
  record "OpenH264 ($SDK)" "vendored third_party/openh264 (repo @ ${OPENH264_SHA:-cached})"

  # ---------------- hsdaoh stub (no-USB platform) ----------------
  log "=== hsdaoh stub ($SDK) ==="
  if [[ "$(pc_version hsdaoh)" != "" ]]; then
    log "skip (hsdaoh.pc already present)"
  else
    mkdir -p "$PREFIX/lib/pkgconfig" "$PREFIX/include"
    # Hermetic prefix: copy the vendored public headers in.
    cp -R "$REPO_ROOT/third_party/hsdaoh/include/." "$PREFIX/include/"
    "$CC" -target "$TARGET_TRIPLE" -isysroot "$SDK_PATH" \
      -I"$PREFIX/include" \
      -O2 -c "$SCRIPT_DIR/hsdaoh_stub/hsdaoh_stub.c" \
      -o "$DEPS_SRC_DIR/hsdaoh_stub-$SDK.o"
    "$AR" rcs "$PREFIX/lib/libhsdaoh.a" "$DEPS_SRC_DIR/hsdaoh_stub-$SDK.o"
    cat > "$PREFIX/lib/pkgconfig/hsdaoh.pc" <<EOF
prefix=$PREFIX
libdir=\${prefix}/lib
includedir=\${prefix}/include

Name: hsdaoh
Description: hsdaoh iOS no-USB stub (zero devices; USB capture unsupported on iOS)
Version: 0.0.0-ios
Libs: -L\${libdir} -lhsdaoh
Cflags: -I\${includedir}
EOF
  fi
  record "hsdaoh ($SDK)" "iOS no-USB stub (ios/hsdaoh_stub)"

  # ---------------- raylib 5.5 (PLATFORM=SDL, GLES 3.0) ----------------
  log "=== raylib ${RAYLIB_TAG} (PLATFORM=SDL, $SDK) ==="
  RAYLIB_SRC="$REPO_ROOT/.deps/raylib"
  if [[ ! -d "$RAYLIB_SRC/.git" ]]; then
    rm -rf "$RAYLIB_SRC"
    git clone --depth 1 --branch "$RAYLIB_TAG" https://github.com/raysan5/raylib.git "$RAYLIB_SRC"
  fi
  if [[ -n "$(pc_version raylib)" ]]; then
    log "skip (raylib.pc already $(pc_version raylib))"
  else
    rm -rf "$DEPS_SRC_DIR/raylib-build-$SDK"
    # raylib 5.5 bug (same fix as the Android build): rlgl.h has an inverted
    # ES3/non-ES3 branch in rlActiveDrawBuffers(); under ES3 it references
    # glDrawBuffersEXT (ES2 extension symbol) instead of glDrawBuffers.
    sed -i '' 's/glDrawBuffersEXT(count, buffers);/glDrawBuffers(count, buffers);/' \
      "$RAYLIB_SRC/src/rlgl.h"
    # --- iOS patches (idempotent, vendored-tree only, desktop unaffected) ---
    # (1) rlgl.h ES3: the Khronos GLES3/gl3.h + GLES2/gl2ext.h headers do not
    #     exist in Apple SDKs; iOS ships OpenGLES/ES3/{gl,glext}.h instead.
    python3 - "$RAYLIB_SRC/src/rlgl.h" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
old = '''#if defined(GRAPHICS_API_OPENGL_ES3)
    #include <GLES3/gl3.h>              // OpenGL ES 3.0 library
    #define GL_GLEXT_PROTOTYPES
    #include <GLES2/gl2ext.h>           // OpenGL ES 2.0 extensions library
'''
new = '''#if defined(GRAPHICS_API_OPENGL_ES3)
    #if defined(__APPLE__)
        // Apple SDKs ship OpenGLES/ES3 headers, not Khronos GLES3 ones.
        #define GL_GLEXT_PROTOTYPES
        #include <OpenGLES/ES3/gl.h>    // OpenGL ES 3.0 library (iOS)
        #include <OpenGLES/ES3/glext.h> // OpenGL ES 3.0 extensions (iOS)
        // --- MISRC iOS port: Apple's ES3 headers define ONLY the unsuffixed
        // core enums; rlgl.h's ES3 paths also use the Khronos _EXT aliases
        // (rlActiveDrawBuffers color attachments + rlGetGlTextureFormats
        // float formats). Map them to the core names. ---
        #define MISRC_IOS_GLES_EXT_ALIASES 1
        #define GL_COLOR_ATTACHMENT0_EXT GL_COLOR_ATTACHMENT0
        #define GL_COLOR_ATTACHMENT1_EXT GL_COLOR_ATTACHMENT1
        #define GL_COLOR_ATTACHMENT2_EXT GL_COLOR_ATTACHMENT2
        #define GL_COLOR_ATTACHMENT3_EXT GL_COLOR_ATTACHMENT3
        #define GL_COLOR_ATTACHMENT4_EXT GL_COLOR_ATTACHMENT4
        #define GL_COLOR_ATTACHMENT5_EXT GL_COLOR_ATTACHMENT5
        #define GL_COLOR_ATTACHMENT6_EXT GL_COLOR_ATTACHMENT6
        #define GL_COLOR_ATTACHMENT7_EXT GL_COLOR_ATTACHMENT7
        #define GL_RED_EXT GL_RED
        #define GL_R32F_EXT GL_R32F
        #define GL_R16F_EXT GL_R16F
        #define GL_RGB32F_EXT GL_RGB32F
        #define GL_RGB16F_EXT GL_RGB16F
        #define GL_RGBA32F_EXT GL_RGBA32F
        #define GL_RGBA16F_EXT GL_RGBA16F
        #define GL_DEPTH_COMPONENT24_OES GL_DEPTH_COMPONENT24
        // Apple ES3 headers define no unsuffixed 32-bit depth enum (only
        // 16/24/32F); use the Khronos _OES value directly (0x81A7).
        #define GL_DEPTH_COMPONENT32_OES 0x81A7
    #else
        #include <GLES3/gl3.h>              // OpenGL ES 3.0 library
        #define GL_GLEXT_PROTOTYPES
        #include <GLES2/gl2ext.h>           // OpenGL ES 2.0 extensions library
    #endif
'''
if old in s:
    s = s.replace(old, new, 1)
    open(p, 'w').write(s)
    print('[ios-deps] patched rlgl.h ES3 includes + _EXT aliases for Apple SDKs')
elif 'MISRC_IOS_GLES_EXT_ALIASES' in s:
    # An earlier revision of the alias list missed the depth-component _OES
    # names (build failed on exactly those 2 identifiers); append them if
