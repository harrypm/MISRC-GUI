# ---------------- fix cross raylib.pc for Android ----------------
# raylib's CMake install emits a Desktop-style raylib.pc: `Requires.private:
# glfw3` and empty `Libs.private`. That is WRONG for the PLATFORM=Android
# build (rcore_android.c uses EGL/ANativeWindow, not glfw). With our cross
# pkg-config wrapper forcing --static, the bogus glfw3 require makes
# `pkg-config --static --cflags/libs raylib` fail, and Meson then falls back to
# CMake and picks up a HOST x86_64 /usr/local/lib/libraylib.a (arch mismatch).
# Fix: drop the glfw3 require and record the real Android platform libs the
# static libraylib.a needs. Run unconditionally so reruns stay correct.
RAYLIB_PC="$DEPS_PREFIX/lib/pkgconfig/raylib.pc"
if [[ -f "$RAYLIB_PC" ]]; then
  sed -i '/^Requires.private: glfw3/d' "$RAYLIB_PC"
  # If Libs.private is empty, fill in the rcore_android.c platform deps.
  if grep -q '^Libs.private: *$' "$RAYLIB_PC"; then
    sed -i 's|^Libs.private: *$|Libs.private: -lm -llog -landroid -lEGL -lGLESv2 -lOpenSLES -latomic|' "$RAYLIB_PC"
  fi
  log "patched raylib.pc (removed glfw3 require; set Android Libs.private)"
fi

