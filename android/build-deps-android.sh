#!/usr/bin/env bash
# Cross-build the six MISRC GUI dependencies for Android arm64-v8a (API 30)
# into .deps/install-android-arm64. Mirrors scripts/build-appimage-local.sh
# and the main-branch CI (build.yml) dep builds, but adds the NDK toolchain.
#
# Deps (all built static):
#   libFLAC 1.5.0   - hard-required by meson.build (flac.pc must report 1.5.0)
#   FFTW 3.3.10     - single-precision (fftw3f), required by misrc_gui
#   libsoxr 0.1.3   - optional resampler (LIBSOXR_ENABLED)
#   libusb 1.0.27   - Android backend (highest risk; FX3/DdD/hsdaoh depend on it)
#   hsdaoh          - vendored (third_party/hsdaoh); links libusb + libFLAC
#   raylib 5.5      - PLATFORM=Android, GLES 3.0, rcore_android.c
#
# Env:
#   ANDROID_NDK_HOME - NDK root (required)
#   DEPS_PREFIX      - install prefix (default: $REPO_ROOT/.deps/install-android-arm64)
#   DEPS_SRC_DIR     - source/build dir (default: $REPO_ROOT/.deps/src-android-arm64)
#   JOBS             - parallel build count (default: nproc)
#
# Idempotent: a dep is skipped if its installed .pc file already reports the
# expected version, so reruns are cheap and safe.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"

: "${ANDROID_NDK_HOME:?Set ANDROID_NDK_HOME (e.g. ~/Android/Sdk/ndk/25.2.9519653)}"
DEPS_PREFIX="${DEPS_PREFIX:-$REPO_ROOT/.deps/install-android-arm64}"
DEPS_SRC_DIR="${DEPS_SRC_DIR:-$REPO_ROOT/.deps/src-android-arm64}"
JOBS="${JOBS:-$(nproc)}"

NDK="$(cd -- "$ANDROID_NDK_HOME" && pwd)"
TOOLCHAIN="$NDK/build/cmake/android.toolchain.cmake"
ABI=arm64-v8a
PLATFORM=android-30

# Sources + expected sha256 (libFLAC sha pinned from main CI build.yml).
FLAC_VERSION=1.5.0
FLAC_TARBALL="flac-${FLAC_VERSION}.tar.xz"
FLAC_URL="https://github.com/xiph/flac/releases/download/${FLAC_VERSION}/${FLAC_TARBALL}"
FLAC_SHA256="f2c1c76592a82ffff8413ba3c4a1299b6c7ab06c734dee03fd88630485c2b920"

FFTW_VERSION=3.3.10
FFTW_TARBALL="fftw-${FFTW_VERSION}.tar.gz"
FFTW_URL="https://fftw.org/${FFTW_TARBALL}"
# fftw sha verified after download (recorded, not pinned — fftw.org tarball is
# regenerated; we pin via github tag instead if the ftp sha drifts).

SOXR_VERSION=0.1.3
SOXR_TARBALL="soxr-${SOXR_VERSION}-Source.tar.xz"
SOXR_URL="https://sourceforge.net/projects/soxr/files/${SOXR_TARBALL}/download"

LIBUSB_VERSION=1.0.27
LIBUSB_TARBALL="libusb-${LIBUSB_VERSION}.tar.bz2"
LIBUSB_URL="https://github.com/libusb/libusb/releases/download/v${LIBUSB_VERSION}/${LIBUSB_TARBALL}"

RAYLIB_TAG=5.5

log() { printf '[android-deps] %s\n' "$*"; }
fail() { printf '[android-deps] ERROR: %s\n' "$*" >&2; exit 1; }

mkdir -p "$DEPS_PREFIX" "$DEPS_SRC_DIR"
export PKG_CONFIG_PATH="$DEPS_PREFIX/lib/pkgconfig:$DEPS_PREFIX/lib64/pkgconfig:${PKG_CONFIG_PATH:-}"
export CMAKE_PREFIX_PATH="$DEPS_PREFIX:${CMAKE_PREFIX_PATH:-}"

# Common CMake cross-compile flags.
cmake_x() {
  cmake "$@" \
    -DCMAKE_TOOLCHAIN_FILE="$TOOLCHAIN" \
    -DANDROID_ABI="$ABI" \
    -DANDROID_PLATFORM="$PLATFORM" \
    -DANDROID_NDK="$NDK" \
    -DCMAKE_BUILD_TYPE=Release \
    -DBUILD_SHARED_LIBS=OFF \
    -DCMAKE_INSTALL_PREFIX="$DEPS_PREFIX" \
    -DCMAKE_FIND_ROOT_PATH="$DEPS_PREFIX"
}

# download <url> <out> [sha256]
download() {
  local url="$1" out="$2" sha="${3:-}"
  if [[ -f "$out" && -s "$out" ]]; then
    log "cached $(basename "$out")"
  else
    log "downloading $(basename "$out")"
    curl -fL --retry 3 -o "$out" "$url"
  fi
  if [[ -n "$sha" ]]; then
    local actual
    actual="$(sha256sum "$out" | awk '{print $1}')"
    [[ "$actual" == "$sha" ]] || fail "$(basename "$out") sha256 mismatch: expected $sha got $actual"
    log "sha256 ok $(basename "$out")"
  fi
}

# pc_version <name> -> echoes version or empty.
# IMPORTANT: use the cross wrapper (DEPS_PREFIX-only PKG_CONFIG_LIBDIR) so we
# only see cross-built libs, never the host x86_64 system .pc files. Otherwise
# the idempotency check falsely skips the build when the host has the same lib.
pc_version() { DEPS_PREFIX="$DEPS_PREFIX" "$SCRIPT_DIR/android-pkg-config" --modversion "$1" 2>/dev/null || true; }

VERS_FILE="$SCRIPT_DIR/deps-versions.txt"
{
  echo "# MISRC GUI Android arm64-v8a cross deps — versions + sources"
  echo "# Generated by android/build-deps-android.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# NDK: $NDK ($(grep -i Pkg.Revision "$NDK/source.properties" | awk '{print $NF}'))"
  echo "# ABI: $ABI  PLATFORM: $PLATFORM"
  echo
} > "$VERS_FILE"
record() { printf '%-18s %s\n' "$1" "$2" >> "$VERS_FILE"; }

# ---------------- libFLAC 1.5.0 ----------------
log "=== libFLAC ${FLAC_VERSION} ==="
if [[ "$(pc_version flac)" == "${FLAC_VERSION}" ]]; then
  log "skip (flac.pc already ${FLAC_VERSION})"
else
  download "$FLAC_URL" "$DEPS_SRC_DIR/$FLAC_TARBALL" "$FLAC_SHA256"
  rm -rf "$DEPS_SRC_DIR/flac-src" "$DEPS_SRC_DIR/flac-build"
  mkdir -p "$DEPS_SRC_DIR/flac-src"
  tar -xf "$DEPS_SRC_DIR/$FLAC_TARBALL" -C "$DEPS_SRC_DIR/flac-src" --strip-components=1
  cmake_x -S "$DEPS_SRC_DIR/flac-src" -B "$DEPS_SRC_DIR/flac-build" \
    -DWITH_OGG=OFF -DBUILD_TESTING=OFF -DINSTALL_MANPAGES=OFF
  cmake --build "$DEPS_SRC_DIR/flac-build" --parallel "$JOBS"
  cmake --install "$DEPS_SRC_DIR/flac-build"
fi
record "libFLAC" "${FLAC_VERSION} (sha256 ${FLAC_SHA256})"

# ---------------- FFTW 3.3.10 (single precision -> fftw3f) ----------------
log "=== FFTW ${FFTW_VERSION} (fftw3f) ==="
if [[ -n "$(pc_version fftw3f)" ]]; then
  log "skip (fftw3f.pc already $(pc_version fftw3f))"
else
  download "$FFTW_URL" "$DEPS_SRC_DIR/$FFTW_TARBALL"
  FFTW_SHA="$(sha256sum "$DEPS_SRC_DIR/$FFTW_TARBALL" | awk '{print $1}')"
  rm -rf "$DEPS_SRC_DIR/fftw-src" "$DEPS_SRC_DIR/fftw-build"
  mkdir -p "$DEPS_SRC_DIR/fftw-src"
  tar -xf "$DEPS_SRC_DIR/$FFTW_TARBALL" -C "$DEPS_SRC_DIR/fftw-src" --strip-components=1
  # ENABLE_FLOAT=ON builds libfftw3f (single precision) + fftw3f.pc.
  cmake_x -S "$DEPS_SRC_DIR/fftw-src" -B "$DEPS_SRC_DIR/fftw-build" \
    -DENABLE_FLOAT=ON -DENABLE_MPI=OFF -DENABLE_OPENMP=OFF \
    -DBUILD_TESTS=OFF -DBUILD_SHARED_LIBS=OFF
  cmake --build "$DEPS_SRC_DIR/fftw-build" --parallel "$JOBS"
  cmake --install "$DEPS_SRC_DIR/fftw-build"
fi
record "FFTW (fftw3f)" "${FFTW_VERSION} (sha256 ${FFTW_SHA:-$(sha256sum "$DEPS_SRC_DIR/$FFTW_TARBALL" 2>/dev/null | awk '{print $1}')})"

# ---------------- libsoxr 0.1.3 ----------------
log "=== libsoxr ${SOXR_VERSION} ==="
if [[ -n "$(pc_version soxr)" ]]; then
  log "skip (soxr.pc already $(pc_version soxr))"
else
  download "$SOXR_URL" "$DEPS_SRC_DIR/$SOXR_TARBALL"
  SOXR_SHA="$(sha256sum "$DEPS_SRC_DIR/$SOXR_TARBALL" | awk '{print $1}')"
  rm -rf "$DEPS_SRC_DIR/soxr-src" "$DEPS_SRC_DIR/soxr-build"
  mkdir -p "$DEPS_SRC_DIR/soxr-src"
  tar -xf "$DEPS_SRC_DIR/$SOXR_TARBALL" -C "$DEPS_SRC_DIR/soxr-src" --strip-components=1
  # soxr defaults to AVR (no SIMD); on aarch64 let it use NEON via WITH_SIMD.
  cmake_x -S "$DEPS_SRC_DIR/soxr-src" -B "$DEPS_SRC_DIR/soxr-build" \
    -DBUILD_TESTS=OFF -DWITH_SIMD=ON -DWITH_OPENMP=OFF
  cmake --build "$DEPS_SRC_DIR/soxr-build" --parallel "$JOBS"
  cmake --install "$DEPS_SRC_DIR/soxr-build"
fi
